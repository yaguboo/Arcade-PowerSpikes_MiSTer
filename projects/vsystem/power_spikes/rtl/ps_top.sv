//============================================================================
//  Power Spikes -- board top
//
//  This is the arcade board and nothing else.  No hps_io, no ioctl, no APF,
//  no MRA: those live in targets/, per root CLAUDE.md section 4.  What
//  crosses this boundary is a neutral memory port (mem_*), neutral inputs,
//  and video/audio out.
//
//  ---- clocking ----------------------------------------------------------
//  clk = 40.000 MHz, and every board clock divides from it exactly:
//
//      68000    10.000 MHz   / 4     HW_CONFIRMED (20 MHz XTAL / 2)
//      Z80       5.000 MHz   / 8     HW_CONFIRMED (20 MHz XTAL / 4)
//      YM2610    8.000 MHz   / 5     HW_CONFIRMED (own 8 MHz XTAL)
//
//  The pixel clock does not divide from it: the board has a second crystal
//  (14.31818 MHz) and 7.159090 MHz is not a rational divisor of 40 MHz by
//  any small integer.  It is generated by a fractional enable instead --
//  add 63, wrap at 352 -- which gives exactly 40e6 * 63/352 = 7.1590909 MHz
//  on average, with pulses alternating 5 and 6 clocks apart.
//
//  Why one clock domain and not two: the alternative is a second PLL output
//  at 57.27 MHz and a real CDC at every dual-port RAM.  Root CLAUDE.md 1.5
//  and section 2 both treat clock/CDC structure as the highest-risk thing to
//  get wrong, and the jitter here is 12.5 ns on a 139.7 ns pixel, which the
//  scaler resamples away.  See docs/DECISIONS.md.
//
//  ---- what is implemented ----------------------------------------------
//      68000, full address decode, all board RAM      yes
//      video timing, tilemap, palette                 yes
//      VS8904/8905 sprites                            yes
//      Z80 + YM2610                                   yes
//============================================================================
