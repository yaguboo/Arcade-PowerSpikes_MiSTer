  // ---------------------------------------------------------------------
  // VBlank interrupt.  MAME uses `irq1_line_hold`, and HOLD_LINE means held
  // until the CPU ACKNOWLEDGES it -- MAME clears it in its IRQ callback.
  //
  // This used to clear it at the END OF VBLANK instead, on the reasoning that
  // fx68k did not expose an acknowledge and "the game's handler always
  // completes well inside one frame".  That was tagged INFERRED and it was
  // wrong in a way that mattered: the handler completes well inside VBLANK,
  // returning around line 7 of 16, and the interrupt was still asserted --
  // so the 68000 took it again immediately and ran the whole handler a
  // second time, every frame.
  //
  // fx68k does announce the acknowledge; the wrapper simply was not passing
  // it out.  FC = 111 with AS low is an interrupt acknowledge cycle.
  // docs/DEBUG_LOG.md O10.
  // ---------------------------------------------------------------------
  //
  // Cleared at the END of the acknowledge cycle, not at its start.  Dropping
  // the level WHILE the 68000 is acknowledging lets it sample level 0 and
  // take a spurious interrupt instead: the first version cleared on the
  // `cpu_iack` level and the board ran for one frame and then froze, with the
  // last captured frame showing zero ROM fetches in its vblank.
  //
  // There used to be a fallback here: if the acknowledge was never seen, the
  // level was dropped at the end of vblank, so that a missed IACK degraded to
  // the old double-handler behaviour instead of a frozen board.  Real
  // hardware has no such path -- the flip-flop is cleared by the acknowledge
  // and by nothing else -- and on the board the acknowledge arrives exactly
  // once a frame (overlay row 68, DEBUG_LOG O22), so it was removed
  // 2026-10-06.  `pend_eovb` below counts the frames in which it WOULD have
  // fired, so if the acknowledge is ever lost again it is visible as a
  // number and not only as a freeze.
  //
  // Set only while the 68000 is running.  A paused CPU (OSD pause, the R
  // button, a ROM download) sees no time pass, and an interrupt latched
  // during the pause would otherwise be taken the moment it resumed -- in
  // the middle of a displayed frame, which the fallback used to hide by
  // dropping it at the end of vblank.  While the CPU runs ce_en is 1 and
  // this is exactly the hardware's behaviour.
  reg vbl_irq, vblank_d, iack_q;
  wire iack_end = iack_q && !cpu_iack;
  always @(posedge clk) begin
    if (rst) begin
      vbl_irq  <= 1'b0;
      vblank_d <= 1'b0;
      iack_q   <= 1'b0;
    end else begin
      vblank_d <= vblank;
      iack_q   <= cpu_iack;
      if (vblank_start && ce_en) vbl_irq <= 1'b1;
      else if (iack_end)         vbl_irq <= 1'b0;  // acknowledge ended
    end
  end

  // Frames whose vblank ended with the interrupt still pending: exactly the
  // frames the old fallback fired on.  Only counted while the CPU runs.
  reg [7:0] pend_eovb;
  always @(posedge clk) begin
    if (rst) pend_eovb <= 8'd0;
    else if (vblank_d && !vblank && vbl_irq && !iack_end && ce_en &&
             pend_eovb != 8'hFF)
      pend_eovb <= pend_eovb + 8'd1;
  end

  // How many times the 68000 acknowledges an interrupt per frame.  One is
  // correct.  More than one is the bug above, and this is how it is told
  // apart from "the CPU is simply slow", which the same symptom looks like.
  reg [7:0] iack_cnt, dbg_iack_cnt;
  always @(posedge clk) begin
    if (rst) begin
      iack_cnt <= 8'd0; dbg_iack_cnt <= 8'd0;
    end else begin
      if (vblank_start) begin
        dbg_iack_cnt <= iack_cnt;
        iack_cnt     <= 8'd0;
      end else if (cpu_iack && !iack_q && iack_cnt != 8'hFF) begin
        iack_cnt <= iack_cnt + 8'd1;
      end
    end
  end

  // The same count, accumulated: a screenshot of row 68 is one frame, these
  // are every frame since reset.  Frames with no IACK include the boot
  // frames before the game enables interrupts, and every paused frame -- so
  // read this one as "stops increasing", not as "is zero".
  reg [15:0] n_iack0;
  reg [7:0]  n_iack2;
  always @(posedge clk) begin
    if (rst) begin
      n_iack0 <= 16'd0; n_iack2 <= 8'd0;
    end else if (vblank_start) begin
      if (iack_cnt == 8'd0 && n_iack0 != 16'hFFFF) n_iack0 <= n_iack0 + 16'd1;
      if (iack_cnt >= 8'd2 && n_iack2 != 8'hFF)   n_iack2 <= n_iack2 + 8'd1;
    end
  end
  assign dbg_iack_x = {n_iack0, pend_eovb, n_iack2};

  // ---------------------------------------------------------------------
  // Video
  // ---------------------------------------------------------------------
  wire [24:0] gfx1_a, gfx2_a;
  wire [15:0] gfx1_q, gfx2_q;
  wire        gfx1_req, gfx1_ack, gfx2_req, gfx2_ack;
  wire [15:0] spr_drawn, spr_hit, spr_overrun;
  wire [15:0] spr_nonrom, spr_workload;
  wire [15:0] spr_snap1, spr_snap2;

