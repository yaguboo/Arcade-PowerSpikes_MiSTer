  // ---------------------------------------------------------------------
  // Clock enables
  // ---------------------------------------------------------------------
  // The DEBUG pause bit is DELAYED, and that is the whole point of it.
  // Only `pause_dbg` goes through this.  The player's pause (`pause`: the R
  // button and "Pause when OSD open") must act at once -- until 2026-09-15 it
  // was OR-ed into the same input and so did nothing for the first ~50 s
  // after every load.
  //
  // Pausing from reset freezes the 68000 before it has booted, so the screen
  // stays black and there is nothing to photograph -- tried, on hardware.
  // What the measurement needs is the opposite: let the game run into the
  // attract, reach a sprite-dense scene, and only then stop the CPU.  The
  // video engines keep scanning and keep contending for SDRAM, so the picture
  // is static while the renderer is still live, and two screenshots then
  // differ ONLY by what the renderer does differently between frames.
  //
  // ~50 s at 61.31 Hz lands in the demo match, which MAME's own dump shows
  // carrying 71 active sprites against 7 on the title screens.
  localparam int PAUSE_DELAY_FRAMES = 3065;
  reg [11:0] pause_fr;
  reg        pause_armed;
  always @(posedge clk) begin
    if (rst) begin
      pause_fr    <= 12'd0;
      pause_armed <= 1'b0;
    end else if (vblank_start && !pause_armed) begin
      if (pause_fr == PAUSE_DELAY_FRAMES[11:0]) pause_armed <= 1'b1;
      else                                      pause_fr <= pause_fr + 12'd1;
    end
  end

  wire ce_en = ~(pause | (pause_dbg & pause_armed)) & ~dl_active;

  // Fractional pixel enable: 40 MHz * 63/352 = 7.1590909 MHz.
  reg [8:0] pixacc;
  reg       ce_pix_r;
  always @(posedge clk) begin
    if (rst) begin
      pixacc   <= 9'd0;
      ce_pix_r <= 1'b0;
    end else begin
      if (pixacc + 9'd63 >= 9'd352) begin
        pixacc   <= pixacc + 9'd63 - 9'd352;
        ce_pix_r <= 1'b1;
      end else begin
        pixacc   <= pixacc + 9'd63;
        ce_pix_r <= 1'b0;
      end
    end
  end
  assign ce_pix = ce_pix_r;

